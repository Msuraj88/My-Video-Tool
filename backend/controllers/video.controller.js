const { preprocessForNarration } = require('../services/scriptPreprocessor.service');
const { processScript } = require('../services/scriptSplitter.service');
const { generateSceneDirection } = require('../services/sceneDirector');
const { buildScenePrompt } = require('../services/promptBuilder');
const { generateAndSaveAudio } = require('../services/audioGeneration.service');
const { generateAndSaveSceneImage } = require('../services/imageGeneration.service');
const { overlaySceneText } = require('../services/textOverlay');
const { createSceneVideo, concatenateVideos } = require('../utils/videoGenerator');
const path = require('path');

const MAX_HEADLINE_CHARS = 50; // for text overlay headline

/**
 * Main orchestration controller to generate a full video from a provided script.
 * 
 * Pipeline: script → scene splitter → scene director → prompt builder → image generation
 * → text overlay (numbers/headlines) → scene video → final video
 */
exports.generateVideo = async (req, res) => {
    try {
        const { script } = req.body;

        if (!script || typeof script !== 'string') {
            return res.status(400).json({ error: 'A valid script string is required in the request body.' });
        }

        console.log('--- STARTING VIDEO GENERATION PIPELINE ---');

        // Step 1: Preprocess script for pacing, then split into scenes
        console.log('Step 1: Preprocessing script for narration pacing...');
        const preprocessedScript = preprocessForNarration(script);
        console.log('Step 2: Splitting script into scenes (10–15 words)...');
        const scenes = processScript(preprocessedScript);

        if (scenes.length === 0) {
            return res.status(400).json({ error: 'The provided script resulted in zero scenes.' });
        }

        console.log(`Script split into ${scenes.length} scenes.`);

        const sceneVideoPaths = [];
        const previousScenes = [];

        // Process each scene: scene director → prompt builder (with variation + memory) → image generator
        for (let i = 0; i < scenes.length; i++) {
            const scene = scenes[i];
            const sceneName = `scene_${scene.scene_number}`;

            console.log(`\n--- Processing Scene ${scene.scene_number}/${scenes.length} ---`);

            // Scene Director: extract numbers for text overlay (no numbers in image prompt)
            const sceneDirection = generateSceneDirection(scene.text);
            // OpenAI Scene Prompt Generator: sentence → visual scene description → image prompt
            const { prompt: imagePrompt, negativePrompt, sceneMemory } = await buildScenePrompt(scene.text, {
                sceneIndex: i,
                previousScenes: [...previousScenes]
            });
            previousScenes.push(sceneMemory);

            // Debug logging before image generation
            console.log('SCENE DIRECTION:', JSON.stringify(sceneDirection, null, 2));
            console.log('FINAL PROMPT:', imagePrompt);

            // Generate Audio
            const audioResult = await generateAndSaveAudio(scene.text, sceneName);
            if (audioResult.error) {
                console.error(`Pipeline aborting: Audio generation failed for ${sceneName}`, audioResult.details);
                return res.status(500).json({
                    error: `Failed to generate audio for scene ${scene.scene_number}`,
                    details: audioResult
                });
            }
            const audioPath = audioResult.filePath;

            // Generate Image (no text in prompt; overlay added next; negative prompt to avoid stock look)
            const imagePath = await generateAndSaveSceneImage(imagePrompt, sceneName, { negativePrompt });

            // Text overlay: add headline and numbers so they are not generated by the image model
            const sceneData = {
                headline: scene.text.length > MAX_HEADLINE_CHARS ? scene.text.slice(0, MAX_HEADLINE_CHARS) + '…' : scene.text,
                numbers: sceneDirection.numbers || []
            };
            const imageWithOverlay = await overlaySceneText(imagePath, sceneData);

            // Merge into Scene Video using overlaid image
            const sceneVideoPath = await createSceneVideo(imageWithOverlay, audioPath, sceneName);
            sceneVideoPaths.push(sceneVideoPath);

            console.log(`Completed ${sceneName}`);
        }

        // Step 3: Concatenate all scene videos
        console.log('\n--- Finalizing Video ---');
        console.log('Step 3: Concatenating all scenes into master video...');

        const outputFilename = `final_video_${Date.now()}.mp4`;
        const outputPath = path.join(__dirname, '../temp/videos', outputFilename);

        const finalVideoPath = await concatenateVideos(sceneVideoPaths, outputPath);

        console.log('--- PIPELINE COMPLETE ---');
        console.log(`Final video ready at: ${finalVideoPath}`);

        // Return success response
        // In a real production app, you might upload this to S3 and return the public URL instead of a local path.
        return res.status(200).json({
            message: 'Video generated successfully',
            scenes_processed: scenes.length,
            final_video_path: finalVideoPath
        });

    } catch (error) {
        console.error('Pipeline Error:', error);

        return res.status(500).json({
            error: 'An error occurred during video generation.',
            details: error.message
        });
    }
};
